const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const csv=(name,s)=>({name,mimeType:'text/csv',buffer:Buffer.from(s)});
(async()=>{
 const channel=process.env.PLATI_TEST_BROWSER;
 const b=await chromium.launch({headless:true,...(channel?{channel}:{})});
 try{
  const p=await b.newPage();
  const actions=[];
  p.on('request',r=>{if(r.method()==='POST')actions.push(new URL(r.url()).searchParams.get('action'));});
  await p.goto('http://127.0.0.1:18778/');
  await p.locator('[name=username]').fill('import_test');
  await p.locator('[name=password]').fill('Local-import-test-2026!');
  const login=p.waitForResponse(r=>r.url().includes('action=login'));
  await p.locator('#loginForm button').click();
  assert.equal((await login).status(),200);
  await p.locator('[data-view=imports]').click();
  const omc=p.locator('.import-grid .card').nth(1).locator('input[type=file]');
  const site=p.locator('.import-grid .card').nth(0).locator('input[type=file]');
  const omcFile=csv('test-omc.csv','data_doc;nr_doc;partener;val_mon;rest_de_incasat;comisionar;eu_punct_lucru;obs_txt;magazie_sursa\n2026-11-10;GPD 901234;NUME TEST;123.45;0;SITE GOLDENDRINKS;SITE;901234567;\n');
  const siteFile=csv('test-site.csv','ID comanda;Data;Data platii;Valoare comanda;AWB;Tip client;Nume client;Nume companie;Metoda de plata;ID Tranzactie\n901234567;2026-11-10;;123.45;;Persoana fizica;NUME TEST;;Plata in sistem ramburs;\n');
  const go=source=>p.getByRole('form',{name:'Import '+source,exact:true}).getByRole('button',{name:'Importă',exact:true});
  await go('SITE').waitFor();
  for(const source of ['SITE','OMC','FAN','NETOPIA'])assert.equal(await go(source).count(),1);
  const api=action=>p.evaluate(async x=>(await (await fetch('api.php?action='+x)).json()).data,action);
  await omc.setInputFiles(omcFile);
  await site.setInputFiles([siteFile,csv('invalid-site.csv','ID comanda;Data\n901234567;2026-11-10\n')]);
  await go('SITE').click();
  await p.getByRole('heading',{name:'Import oprit'}).waitFor();
  assert.match(await p.locator('#dialogBody').innerText(),/Lipsesc coloanele/);
  assert.equal((await api('imports')).length,0);
  assert.equal(await omc.evaluate(e=>e.files.length),1);
  await p.locator('#dialog .close').click();
  await go('OMC').click();
  await p.getByRole('heading',{name:'Rezultatul importului'}).waitFor();
  assert.equal((await api('imports')).length,1);
  assert.equal(await site.evaluate(e=>e.files.length),2);
  await p.locator('#dialog .close').click();
  await site.setInputFiles(siteFile);
  await go('SITE').click();
  await p.getByRole('heading',{name:'Rezultatul importului'}).waitFor();
  assert.match(await p.locator('#dialogBody').innerText(),/Comenzi: 1/);
  await p.locator('#dialog .close').click();
  assert.equal((await api('imports')).length,2);
  assert.equal((await api('orders&status=all')).rows[0].invoice_number,'GPD 901234');
  await omc.setInputFiles(omcFile);
  await go('OMC').click();
  await p.getByText('Fișier deja importat; datele au fost păstrate.').waitFor();
  assert.deepEqual(actions,['login','import_files','import_files','import_files','import_files']);
  console.log('PASS: four dedicated buttons, one POST per source, atomic validation, preserved selections, matching and duplicate detection.');
  await p.locator('#dialog .close').click();

  const fanForm=p.getByRole('form',{name:'Import FAN',exact:true});
  const upload=async(source,input,file)=>{
   await input.setInputFiles(file);
   await go(source).click();
   await p.getByRole('heading',{name:'Rezultatul importului'}).waitFor();
   await p.locator('#dialog .close').click();
  };
  const fan=fanForm.locator('input[type=file]');
  const fanFinancial=(name,rows)=>csv(name,'Localitate;Data AWB;Suma incasata;AWB;Expeditor;Destinatar;Continut;Persoana contact destinatar;Data virament;Card;PersoanaE;Ramburs la AWB;AWB retur;Data tranzactie\n'+rows.map(([awb,sum,date])=>`TEST;10-11-26;${sum};${awb};TEST;TEST;COMANDA 901234568;;${date};;;;;\n`).join(''));
  const [a,bad,ret]=['7000999900001','7000999900002','7000999900003'];
  const initial=fanFinancial('test-financiar.csv',[[a,'123,45','12-11-26'],[bad,'123,44','12-11-26'],[ret,'123,45','12-11-26']]);
  const reasons=async()=>Object.fromEntries((await api('fan_transfer_cases')).map(c=>[c.awb,c.reasons]));
  const invoice=async number=>(await api('report&mode=all&q='+encodeURIComponent(number))).rows[0];
  await upload('OMC',omc,csv('test-omc-fan.csv','data_doc;nr_doc;partener;val_mon;rest_de_incasat;comisionar;eu_punct_lucru;obs_txt;magazie_sursa\n2026-11-10;GPD 901235;NUME ALFA;123.44;0;SITE GOLDENDRINKS;SITE;901234568;\n2026-11-10;GPD 901236;NUME BETA;123.45;123.45;SITE GOLDENDRINKS;SITE;;\n'));
  await upload('SITE',site,csv('test-site-fan.csv',`ID comanda;Data;Data platii;Valoare comanda;AWB;Tip client;Nume client;Nume companie;Metoda de plata;ID Tranzactie\n901234568;2026-11-10;;123.45;${a};Persoana fizica;NUME ALFA;;Plata in sistem ramburs;\n`));
  await upload('FAN',fan,initial);
  assert.deepEqual(await reasons(),{[a]:['waiting_awb'],[bad]:['waiting_awb'],[ret]:['waiting_awb']});
  await upload('FAN',fan,csv('test-operational.csv',`AWB;Data AWB;Client Dest.;Continut;Status Livrare;Ramburs;Data Virament;Tip Serviciu\n${a};10-11-26;ALT DESTINATAR;COMANDA 901234568;Livrat;123,45;11-11-26;Cont Colector\n${bad};10-11-26;NUME BETA;;Livrat;123,45;;Cont Colector\n${ret};10-11-26;NUME TEST;;Retur;123,45;;Cont Colector\n`));
  assert.deepEqual(await reasons(),{[bad]:['amount_mismatch'],[ret]:['returned']});
  const historic=await invoice('GPD 901235');
  assert.equal(historic.awb,a);
  assert.equal(historic.transfer_date,'2026-11-12');
  assert.equal(+historic.balance_cents,0);
  assert.equal(+historic.amount_cents,12344);
  assert.equal(+historic.transfer_amount_cents,12345);
  assert.equal((await invoice('GPD 901236')).awb,null);
  await upload('FAN',fan,fanFinancial('test-corectat.csv',[[bad,'123,45','12-11-26']]));
  assert.equal((await invoice('GPD 901236')).awb,bad);
  assert.deepEqual(await reasons(),{[ret]:['returned']});

  const conflict=fanFinancial('test-alta-data.csv',[[a,'123,45','13-11-26']]);
  await upload('FAN',fan,conflict);
  assert.equal((await invoice('GPD 901235')).transfer_date,'2026-11-12');
  assert.deepEqual(await reasons(),{[a]:['date_conflict'],[ret]:['returned']});
  await fanForm.getByRole('button',{name:'Verifică viramentele'}).click();
  await p.getByRole('button',{name:'Alege 13.11.2026'}).click();
  await p.getByText('Data viramentului a fost salvată.').waitFor();
  await p.locator('#dialog .close').click();
  assert.equal((await invoice('GPD 901235')).transfer_date,'2026-11-13');
  await upload('FAN',fan,conflict);
  await upload('FAN',fan,fanFinancial('test-aceeasi-data-alt-export.csv',[[a,'123,45','12-11-26'],[bad,'123,45','12-11-26']]));
  assert.deepEqual(await reasons(),{[ret]:['returned']});
  assert.equal((await invoice('GPD 901235')).transfer_date,'2026-11-13');
  console.log('PASS: FAN financial-first, operational-first, exact cents, returned AWB review, safe historical matching, date conflict selection and repeat imports.');
 }finally{await b.close();}
})().catch(e=>{console.error(e);process.exit(1)});
